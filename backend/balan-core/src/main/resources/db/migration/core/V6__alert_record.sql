CREATE TABLE IF NOT EXISTS alert_record (
    id               BIGINT        NOT NULL AUTO_INCREMENT COMMENT '告警ID',
    station_id       BIGINT        NOT NULL COMMENT '场站ID',
    charger_id       BIGINT        DEFAULT NULL COMMENT '设备ID',
    device_no        VARCHAR(64)   DEFAULT NULL COMMENT '设备编号',
    port_no          INT           DEFAULT NULL COMMENT '端口号，设备级告警为空',
    alert_type       VARCHAR(30)   NOT NULL COMMENT 'OVER_TEMP/OVER_CURRENT/OVER_VOLTAGE/UNDER_VOLTAGE/OVERLOAD/OFFLINE/PORT_FAULT/STATE_MISMATCH',
    alert_level      VARCHAR(20)   NOT NULL DEFAULT 'MAJOR' COMMENT 'CRITICAL / MAJOR / INFO',
    status           VARCHAR(20)   NOT NULL DEFAULT 'OPEN' COMMENT 'OPEN / ACKNOWLEDGED / RESOLVED',
    source           VARCHAR(20)   NOT NULL DEFAULT 'PLATFORM' COMMENT 'PLATFORM 平台判定 / DEVICE 设备上报',
    content          VARCHAR(500)  DEFAULT NULL COMMENT '告警内容',
    metric_value     DECIMAL(14,4) DEFAULT NULL COMMENT '触发值',
    threshold_value  DECIMAL(14,4) DEFAULT NULL COMMENT '阈值',
    occurred_at      DATETIME      NOT NULL COMMENT '首次发生时间',
    last_occurred_at DATETIME      DEFAULT NULL COMMENT '最近发生时间',
    acknowledged_by  VARCHAR(64)   DEFAULT NULL COMMENT '确认人',
    acknowledged_at  DATETIME      DEFAULT NULL COMMENT '确认时间',
    resolved_by      VARCHAR(64)   DEFAULT NULL COMMENT '恢复人，自动恢复为 system',
    resolved_at      DATETIME      DEFAULT NULL COMMENT '恢复时间',
    create_time      DATETIME      DEFAULT CURRENT_TIMESTAMP,
    update_time      DATETIME      DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    del_flag         CHAR(1)       NOT NULL DEFAULT '0' COMMENT '0存在 2删除',
    PRIMARY KEY (id),
    KEY idx_alert_station_time (station_id, occurred_at),
    KEY idx_alert_status_time (status, occurred_at),
    KEY idx_alert_active (charger_id, port_no, alert_type, status),
    KEY idx_alert_type_time (alert_type, occurred_at)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '告警记录';
